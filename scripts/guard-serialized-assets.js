"use strict";
/**
 * PreToolUse: refuse text edits to the files Unity serializes.
 *
 * A .unity or .prefab file is YAML, so it looks editable. What it actually
 * contains is a graph of fileIDs and GUIDs, and a change that reads correctly
 * can detach a reference, drop a component, or leave the file in a state the
 * Editor silently rewrites on next save. The failure does not appear at the
 * edit; it appears later, somewhere else, as a missing script.
 *
 * .meta files are worse: the GUID in one is the identity every scene and prefab
 * in the project refers to. Writing one by hand orphans every reference to the
 * asset at once.
 *
 * So this hook draws a line. Code is the model's; serialized state is the
 * Editor's. That division is also what makes the split of work in a repository
 * a verifiable fact rather than a claim.
 */

const io = require("./lib/hook-io.js");
const unity = require("./lib/unity-project.js");

const HANDOFF =
  "Do not work around this by editing the file another way. Use the " +
  "`/unity-kit:editor-handoff` skill to write the exact Editor steps for the user " +
  "instead, and continue with the C# side of the task.";

io.run((payload) => {
  const file = io.targetFile(payload);
  if (!file) return null;

  const normalized = io.normalize(file);
  const lower = normalized.toLowerCase();
  const base = lower.split("/").pop();
  const ext = base.includes(".") ? base.slice(base.lastIndexOf(".")) : "";

  const root = unity.findProjectRoot(io.path.dirname(file)) || unity.findProjectRoot(payload.cwd);
  if (!root) return null;

  // The path relative to the project root, because everything below is decided
  // by where the file sits *in the project*. Matching against the absolute path
  // makes the hook depend on what the project happens to be checked out under --
  // a project in a folder called Temp would switch its own guardrails off.
  const relative = io.normalize(io.path.relative(root, file));
  if (!relative || relative.startsWith("..") || io.path.isAbsolute(relative)) return null;

  // Unity regenerates everything under these, so an edit there is pointless
  // rather than dangerous. Saying nothing is the right amount of noise.
  if (/^(library|temp|logs|obj|bin|usersettings)\//i.test(relative)) return null;

  if (ext === ".meta") {
    return io.deny(
      `${base} is a Unity .meta file. The GUID in it is the identity every scene, ` +
        "prefab and asset reference in the project points at, and Unity writes these " +
        "files itself when assets are added, moved or renamed in the Editor. Editing " +
        "one by hand orphans every reference to that asset.\n\n" +
        "To move or rename an asset, do it in the Unity Project window, which moves " +
        "the .meta with it and keeps the GUID. " +
        HANDOFF
    );
  }

  // Checked before the general case: a settings asset is also serialized YAML,
  // but the reason it must not be hand-edited is a different one and the user
  // needs the specific advice.
  if (/^projectsettings\/[^/]+\.asset$/i.test(relative)) {
    return io.deny(
      `${base} is a project settings asset. Unity writes it from the Project Settings ` +
        "window, and several of its fields are index-based, so a hand edit can shift " +
        "unrelated settings. Change it through Edit > Project Settings instead. " +
        HANDOFF
    );
  }

  if (UNITY_OWNED(ext)) {
    const kind =
      ext === ".unity" ? "a scene" : ext === ".prefab" ? "a prefab" : `a serialized ${ext} asset`;
    return io.deny(
      `${base} is ${kind}. Unity serializes it as YAML whose meaning lives in fileIDs ` +
        "and GUIDs, not in the text, so a text edit that reads correctly can still " +
        "detach a reference or drop a component — and the breakage surfaces later, " +
        "in a different file, as a missing script.\n\n" +
        "This change belongs in the Unity Editor. " +
        HANDOFF
    );
  }

  if (/^packages\/manifest\.json$/i.test(relative)) {
    return io.ask(
      "This is the Unity package manifest. Editing it is a normal thing to do, but " +
        "it changes what the Editor compiles against: Unity resolves the change on " +
        "next focus, rewrites packages-lock.json, and a wrong version string leaves " +
        "the project unable to compile until someone opens the Package Manager.\n\n" +
        "Confirm the package name and version are right for this editor version."
    );
  }

  if (/^packages\/packages-lock\.json$/i.test(relative)) {
    return io.ask(
      "packages-lock.json is generated by the Package Manager from manifest.json. " +
        "Hand edits are overwritten on the next resolve. Change manifest.json instead " +
        "unless you are deliberately pinning a resolved hash."
    );
  }

  return null;
});

function UNITY_OWNED(ext) {
  return unity.UNITY_SERIALIZED_EXTENSIONS.has(ext);
}
